"""Static generator contract: render a content snapshot into a fresh output tree."""
from pathlib import Path
from typing import Protocol
import hashlib
import logging
from collections import Counter
import json
import shutil
import tempfile
from progress import stage

class Generator(Protocol):
    def render(self, project: Path, workspace: Path, site_url: str) -> None:
        """Render workspace/docs into workspace/site; raise on failure."""


def validate_site(docs: Path, output: Path):
    """The public URL contract is flat .html pages and unchanged static data/assets."""
    required = {'index.html','compare.html','settings.html','hardware-search.html',
                'boards.html','events.json','intelligence.json','feed.xml','watchlist.xml'}
    for path in docs.rglob('*'):
        if not path.is_file(): continue
        rel = path.relative_to(docs)
        target = output / (rel.with_suffix('.html') if path.suffix == '.md' else rel)
        if not target.is_file() or target.stat().st_size == 0:
            raise RuntimeError(f'Missing/empty output: {target.relative_to(output)}')
        if path.suffix != '.md' and hashlib.sha256(path.read_bytes()).digest() != hashlib.sha256(target.read_bytes()).digest():
            raise RuntimeError(f'Changed static asset: {rel}')
    for name in sorted(required):
        if not (output/name).is_file() or not (output/name).stat().st_size:
            raise RuntimeError(f'Missing/empty required output: {name}')
    for name in ('events.json','intelligence.json'):
        with (output/name).open(encoding='utf-8') as f: data = json.load(f)
        if name == 'intelligence.json' and data.get('schema_version') in (2,3):
            for view in ('data/preferences.json','data/news-view.json') + (('data/activity.json',) if data.get('schema_version') == 3 else ()):
                with (output/view).open(encoding='utf-8') as f: json.load(f)
            import re
            from board_images import GENERATED, git_digest, valid_raster
            for ref in {b['image_url'] for b in data.get('boards', []) if b.get('image_url')}:
                prefix = 'data/board-images/'
                if not ref.startswith(prefix) or not GENERATED.fullmatch(ref[len(prefix):]):
                    raise RuntimeError(f'Invalid board image reference: {ref}')
                image = output/ref
                if not image.is_file():
                    raise RuntimeError(f'Missing board image: {ref}')
                raw = image.read_bytes()
                if git_digest(raw, image.stem) != image.stem or not valid_raster(raw, image.suffix[1:]):
                    raise RuntimeError(f'Invalid board image: {ref}')
            refs = {t['evidence_url'] for t in data['comparison']['targets']}
            for ref in refs:
                if not re.fullmatch(r'data/board-evidence/[a-f0-9]{64}\.json', ref):
                    raise RuntimeError(f'Invalid evidence reference: {ref}')
                file = output/ref
                if not file.is_file() or hashlib.sha256(file.read_bytes()).hexdigest() != file.stem:
                    raise RuntimeError(f'Missing or inconsistent evidence file: {ref}')
    for name, mount in [('compare.html','pulse-comparator'),('settings.html','pulse-settings'),('hardware-search.html','pulse-hardware-search')]:
        if not any(f'id={q}{mount}{q}' in (output/name).read_text(encoding='utf-8') for q in ('"', "'")):
            raise RuntimeError(f'Missing interactive mount: {name} / {mount}')


def content_changes(old: Path, new: Path):
    """Report actual generated byte differences, not mtime or source estimates."""
    previous={p.relative_to(old):p for p in old.rglob('*') if p.is_file()} if old.exists() else {}
    current={p.relative_to(new):p for p in new.rglob('*') if p.is_file()}
    counts=Counter(); boards=Counter()
    for rel,path in current.items():
        prior=previous.get(rel)
        state=('new' if prior is None else 'unchanged' if path.stat().st_size==prior.stat().st_size and hashlib.sha256(path.read_bytes()).digest()==hashlib.sha256(prior.read_bytes()).digest() else 'changed')
        counts[state]+=1
        if state!='unchanged': counts['changed_bytes']+=path.stat().st_size
        if rel.parts[0]=='boards' and rel.suffix=='.html': boards[state]+=1
    for rel in previous.keys()-current.keys():
        counts['removed']+=1
        if rel.parts[0]=='boards' and rel.suffix=='.html': boards['removed']+=1
    return counts,boards


def build_site(project: Path, generator: Generator, site_url: str) -> Path:
    """Clean staged build, validate, then replace local site; failure never publishes."""
    project = project.resolve(); dest = project/'site'
    if dest.is_symlink() or (dest.exists() and not dest.is_dir()):
        raise ValueError('site must be a real directory')
    with tempfile.TemporaryDirectory(prefix='.pulse-build-',dir=project) as tmp:
        work = Path(tmp)
        with stage('Stage portable content'):
            shutil.copytree(project/'docs', work/'docs')
        with stage('Run static renderer'):
            generator.render(project, work, site_url)
        new = work/'site'
        with stage('Validate generated files and assets'):
            validate_site(work/'docs',new)
        with stage('Compare rendered site contents'):
            counts,boards=content_changes(dest,new)
            logging.info('Rendered site: %d new, %d changed, %d unchanged, %d removed',counts['new'],counts['changed'],counts['unchanged'],counts['removed'])
            logging.info('Rendered changed/new bytes: %.2f MiB',counts['changed_bytes']/1048576)
            logging.info('Board HTML: %d new, %d changed, %d unchanged, %d removed',boards['new'],boards['changed'],boards['unchanged'],boards['removed'])
        backup = work/'previous'
        if dest.exists(): dest.rename(backup)
        try: new.rename(dest)
        except BaseException:
            if backup.exists(): backup.rename(dest)
            raise
    return dest
